export function getGarageTaskRating(
  garage: WorkshopGarage,
  category: ServiceCategory
): TaskRating {
  if (garage.taskRatings && garage.taskRatings[category]) {
    return garage.taskRatings[category]!;
  }
  return {
    rating: garage.rating,
    reviewCount: Math.round(garage.reviewCount * 0.25),
    specialtyHighlight: garage.specialistTag || "Standard Workshop Certified Bay",
  };
}

